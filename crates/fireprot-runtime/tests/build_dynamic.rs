#![cfg(target_os = "linux")]
use fireprot_runtime::build_dynamic::DynamicInputs;
use std::{fs, os::unix::fs::PermissionsExt};

// Serialize fork/exec with creation of test scripts: another test thread can
// otherwise fork while a writable script descriptor is still open.
static PROCESS_FIXTURE: std::sync::Mutex<()> = std::sync::Mutex::new(());

#[test]
fn inspects_real_host_elf_and_rejects_non_elf() {
    let _guard = PROCESS_FIXTURE.lock().unwrap();
    let inputs = DynamicInputs {
        inspector: "/usr/bin/ldd".into(),
        objects: vec![std::env::current_exe().unwrap()],
    };
    let first = inputs.identify().unwrap();
    let second = inputs.identify().unwrap();
    assert_eq!(first, second);
    assert!(first.len() >= 3); // inspector, executable, at least its loader/library
    assert!(
        first
            .iter()
            .any(|f| f.canonical_path == std::env::current_exe().unwrap())
    );
    let dir = tempfile::tempdir().unwrap();
    let script = dir.path().join("not-elf");
    fs::write(&script, "#!/bin/sh\necho fake").unwrap();
    assert!(
        DynamicInputs {
            objects: vec![script],
            ..inputs
        }
        .identify()
        .is_err()
    );
}

#[test]
fn library_content_resolution_changes_and_inspector_failures_are_detected() {
    let _guard = PROCESS_FIXTURE.lock().unwrap();
    let dir = tempfile::tempdir().unwrap();
    let library = dir.path().join("library.so");
    fs::write(&library, "first").unwrap();
    let inspector = dir.path().join("inspect");
    // Test-owned paths are generated by tempfile and contain no shell metacharacters.
    fs::write(
        &inspector,
        format!(
            "#!/bin/sh\nprintf 'libx.so => {} (0x123)\\n'\n",
            library.display()
        ),
    )
    .unwrap();
    fs::set_permissions(&inspector, fs::Permissions::from_mode(0o755)).unwrap();
    let input = DynamicInputs {
        inspector: inspector.clone(),
        objects: vec![std::env::current_exe().unwrap()],
    };
    let first = input.identify().unwrap();
    fs::write(&library, "changed").unwrap();
    assert_ne!(input.identify().unwrap(), first);
    fs::remove_file(&library).unwrap();
    assert!(input.identify().is_err());
    fs::write(&inspector, "#!/bin/sh\nprintf 'libx.so => not found\\n'\n").unwrap();
    assert!(input.identify().is_err());
    fs::write(&inspector, "#!/bin/sh\nexit 3\n").unwrap();
    assert!(input.identify().is_err());
}
